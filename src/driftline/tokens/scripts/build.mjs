// Generates dist/tokens.css and dist/tokens.ts from tokens.json. Run: npm run tokens
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { here, loadTokens, resolveTheme } from './lib.mjs';

const t = loadTokens();
const px = (n) => `${n}px`;
const L = [];
L.push(`/* driftline-kit tokens v${t.version} (${t.status}). GENERATED from tokens.json by scripts/build.mjs. Do not edit. */`);

// ---- scales (theme independent)
L.push(':root {');
for (const [k, v] of Object.entries(t.scale.space)) L.push(`  --dl-space-${k}: ${px(v)};`);
for (const [k, v] of Object.entries(t.scale.radius)) L.push(`  --dl-radius-${k}: ${px(v)};`);
for (const [k, v] of Object.entries(t.scale.type)) {
  L.push(`  --dl-type-${k}-size: ${px(v.size)}; --dl-type-${k}-line: ${px(v.line)}; --dl-type-${k}-weight: ${v.weight}; --dl-type-${k}-track: ${v.track}em;`);
}
L.push(`  --dl-font-sans: ${t.scale.font.sans};`, `  --dl-font-mono: ${t.scale.font.mono};`);
for (const [k, v] of Object.entries(t.scale.hit)) L.push(`  --dl-hit-${k}: ${px(v)};`);
for (const [k, v] of Object.entries(t.scale.blur)) L.push(`  --dl-blur-${k}: ${px(v)};`);
for (const [k, v] of Object.entries(t.scale.z)) L.push(`  --dl-z-${k}: ${v};`);
for (const [k, v] of Object.entries(t.motion.duration)) L.push(`  --dl-dur-${k}: ${v}ms;`);
for (const [k, v] of Object.entries(t.motion.ease)) L.push(`  --dl-ease-${k}: ${v};`);
L.push(`  --dl-press-scale: ${t.motion.press.scale};`, `  --dl-press-dur: ${t.motion.press.durationMs}ms;`);
L.push(`  --dl-header-height: ${px(t.component.header.height)}; --dl-pill-height: ${px(t.component.header['pill-height'])}; --dl-dock-height: ${px(t.component.dock.height)};`);
L.push('}');

// ---- density
const dens = (name) => Object.entries(t.scale.density[name]).map(([k, v]) => `  --dl-${k}: ${px(v)};`);
L.push(':root, [data-density="comfortable"] {', ...dens('comfortable'), '}');
for (const d of ['compact', 'stage']) L.push(`[data-density="${d}"] {`, ...dens(d), '}');

// ---- themes (semantic tier)
const names = Object.keys(t.themes);
const themeBlock = (name) => {
  const c = resolveTheme(t, name);
  const mode = t.themes[name].mode;
  const mixPct = mode === 'dark' ? t.component.chip['mix-dark'] : t.component.chip['mix-light'];
  const out = [`  color-scheme: ${mode};`];
  for (const [k, v] of Object.entries(c)) out.push(`  --dl-color-${k}: ${v};`);
  for (const s of ['positive', 'warning', 'danger', 'special', 'accent']) {
    out.push(`  --dl-chip-${s}-bg: color-mix(in srgb, var(--dl-color-${s}) ${mixPct}%, var(--dl-color-surface-solid));`);
    out.push(`  --dl-chip-${s}-border: color-mix(in srgb, var(--dl-color-${s}) ${t.component.chip['border-mix']}%, transparent);`);
  }
  return out;
};
L.push(`:root, [data-theme="${names[0]}"] {`, ...themeBlock(names[0]), '}');
for (const n of names.slice(1)) L.push(`[data-theme="${n}"] {`, ...themeBlock(n), '}');
// no-JS fallback: follow the OS to the fixed day theme
L.push('@media (prefers-color-scheme: light) {', '  :root:not([data-theme]) {', ...themeBlock('utopian-day').map((l) => '  ' + l), '  }', '}');

// ---- component tier (references semantic tokens only)
const ref = (role) => (role.startsWith('#') ? role : t.scale.radius[role] !== undefined ? `var(--dl-radius-${role})` : `var(--dl-color-${role})`);
L.push(':root {');
for (const [comp, props] of Object.entries(t.component)) {
  if (comp === 'chip') continue;
  for (const [k, v] of Object.entries(props)) {
    if (typeof v === 'number') continue;
    L.push(`  --dl-${comp}-${k}: ${ref(v)};`);
  }
}
L.push('}');

// ---- reduced motion: CSS durations collapse; JS springs read useReducedMotion
L.push('@media (prefers-reduced-motion: reduce) {', '  :root { --dl-dur-quick: 1ms; --dl-dur-calm: 1ms; --dl-dur-deliberate: 1ms; --dl-press-scale: 1; }', '}');

const dist = join(here, '..', 'dist');
mkdirSync(dist, { recursive: true });
writeFileSync(join(dist, 'tokens.css'), L.join('\n') + '\n');

const ts = `// GENERATED by scripts/build.mjs from tokens.json. Do not edit.
export const TOKENS_VERSION = ${JSON.stringify(t.version)};
export const THEMES = ${JSON.stringify(names.map((n) => ({ id: n, name: t.themes[n].name, mode: t.themes[n].mode, family: t.themes[n].family, side: t.themes[n].side })), null, 2)} as const;
export const FAMILIES = ${JSON.stringify(Object.entries(t.families).map(([id, f]) => ({ id, name: f.name, tier: f.tier })), null, 2)} as const;
export type FamilyId = (typeof FAMILIES)[number]['id'];
export const THEME_ALIASES: Record<string, string> = ${JSON.stringify(t.aliases)};
export const HAPTIC_LEVELS = ['off', 'light', 'normal', 'strong'] as const;
export type ThemeId = (typeof THEMES)[number]['id'];
export const SPRINGS = ${JSON.stringify(Object.fromEntries(Object.entries(t.motion.spring).map(([k, v]) => { const { use, ...rest } = v; return [k, { type: 'spring', ...rest }]; })), null, 2)} as const;
export const DURATION = ${JSON.stringify(t.motion.duration)} as const;
export const HEADER = ${JSON.stringify(t.motion.header)} as const;
export const ATTENTION = ${JSON.stringify(t.motion.attention)} as const;
export const HOLD = ${JSON.stringify(t.motion.hold)} as const;
export const PRESS = ${JSON.stringify(t.motion.press)} as const;
export const HAPTICS = ${JSON.stringify(Object.fromEntries(Object.entries(t.haptic).map(([k, v]) => [k, v.pattern])))} as const;
export type HapticGrade = keyof typeof HAPTICS;
export const HIT = ${JSON.stringify(t.scale.hit)} as const;
`;
writeFileSync(join(dist, 'tokens.ts'), ts);
console.log(`tokens v${t.version}: ${names.length} themes -> dist/tokens.css (${L.length} lines), dist/tokens.ts`);
